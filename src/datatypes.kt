fun main() {

    var age = 34 //Integer datatype
    var temperature = 25.5 //double
    var number = 67.8F //float values (have to end with f)
    var country = "Kenya" //string. when value is a text. In DOUBLE QUOTES
    var grade = 'A' // this is a character. Letters are called characters
    var isMale = true //this is a boolean. For true or false values

    //Variables SHOULD NEVER be inside double quotes

    println(age)
    println(temperature)
    println(number)
    println(country)
    println(grade)
    println(isMale)



}